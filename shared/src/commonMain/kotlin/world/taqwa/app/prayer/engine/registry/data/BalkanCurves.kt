/**
 * The Balkan authorities' own dawns and nightfalls at the points their tables are printed for
 * (rulings R39, R42): IZ BiH's vaktija for Sarajevo, Banja Luka and Bihać, whose towns are Sarajevo
 * plus whole-minute monthly offsets that drift from the sun by up to 7 min at the dawn, and Kosovo's
 * BIK Takvimi, an old perpetual table computed for 42.5° N 21° E whose imsak runs between 18.5° and
 * 19.7°. With these curves the app starts each prayer where the table prints it rather than at a
 * fixed angle and a margin wide enough for the worst day.
 *
 * Derived parameters, not times: at the table's point and under the engine's exact sun, the sun's
 * depression 25 s before each printed minute (both round to the nearest minute), by R28's slot (the
 * month and day of 2028-01-01 + i); per slot the smallest dawn depression (the latest Fajr) rounded
 * down to a hundredth of a degree, and the largest (the earliest end of eating, the same printed
 * column) and the largest Isha depression rounded up; 29 February from its neighbours; then each the
 * smallest (Fajr) or largest (the end, Isha) of the day before, the day and the day after, so the
 * leap cycle's drift cannot make a start early or the end late. Sources: vaktija.ba's 2026 data
 * (IZ BiH) and dituriaislame.com's Takvimi 2026 (BIK), both restricted: only these depressions are
 * kept; the tables themselves are not committed.
 */
internal object BalkanCurves {
