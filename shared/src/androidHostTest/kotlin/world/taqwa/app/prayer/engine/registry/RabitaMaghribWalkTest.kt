/**
 * Rabita's Maghrib walked day by day from 2026 to 2033 (ruling R155, Europe.RABITA_MAGHRIB_SECONDS). Here, on the JVM
 * only, because it is a sweep of about 100,000 place-days: about 11 s here and over two minutes on the iOS simulator. The
 * engine is common code, so the JVM walk holds the fit for both platforms.
 */
class RabitaMaghribWalkTest {

    @Test
    fun `rabita's maghrib is never before its calendar's rule from 2026 to 2033 at helsinki or across its ride`() {
        // Ruling R155 counts Rabita's Maghrib like any member's start. Its Helsinki calendar's Maghrib is the sun at
        // about -1.22 degrees rounded to the minute: fitted (ruling R42, a derived parameter, never the printed table)
        // as the sun at -1.2183 degrees plus 7 s, rounded, it gives 354 of 2026's 365 printed minutes and the other 11
        // a minute either side; plus 12 s it is at or after all 365. Two calendars stand in for the one of years to
        // come: the calendar regenerated by its rule each year (bounded, plus 12 s), and the calendar kept as it is, as
        // Mawaqit's year-agnostic calendar is (the rule's 2026 minute carried to the same month-day; 29 February has
        // only the first). The member's own day at Helsinki and the cautious day across Helsinki and its ride (the
        // app's places the gate holds, and the envelope's points 30, 45.1 and 69 km out every 45 degrees; at 45.1 and
        // 69 km, past Diyanet's Helsinki unit, the 2026 gate found it early) are never before either on any day of 2026
        // to 2033, November included (the leap-cycle fit of the review of 25 Oct 2026; the 2026 fit ran a minute before
        // the calendar kept as it is in September and October 2028 and 2032).
        val helsinki = GeoPoint(60.1699, 24.9384)
        val zoneId = "Europe/Helsinki"
        val zone = TimeZone.of(zoneId)
        fun rule(date: LocalDate, constant: Double): Instant {
            val noonOffset = zone.offsetAt(date.atTime(12, 0).toInstant(zone)).totalSeconds
            val sun = assertNotNull(SunClock(helsinki.lat, helsinki.lon, date, noonOffset, SunModel.EXACT).altitudeTime(-1.2183, morning = false))
            return Instant.fromEpochSeconds(((sun + constant) / 60.0).roundToLong() * 60L)
        }
        fun calendarBound(date: LocalDate): Instant {
            val regenerated = rule(date, 12.0)
            if (date.month == Month.FEBRUARY && date.day == 29) return regenerated
            val in2026 = LocalDate(2026, date.month, date.day)
            val kept = rule(in2026, 7.0) + (date.toEpochDays() - in2026.toEpochDays()).days
            return maxOf(regenerated, kept)
        }
        val days = generateSequence(LocalDate(2026, 1, 1)) { it.plus(1, DateTimeUnit.DAY) }.takeWhile { it.year <= 2033 }.toList()
        val bounds = days.associateWith { calendarBound(it) }
        val own = Registry.resolve(Place(helsinki.lat, helsinki.lon, zoneId, "FI")).members.first { it.id == "se.rabita" }.method
        for (date in days) {
            val maghrib = DayComputer.compute(own, helsinki, date, zone, AsrSchool.STANDARD, Registry.ramadanCalendar()).maghrib
            assertTrue(maghrib >= bounds.getValue(date), "Rabita's own Maghrib at Helsinki on $date")
        }
        val places = listOf(
            helsinki, GeoPoint(60.15896, 24.86797), GeoPoint(60.25174, 24.88111), GeoPoint(60.17239, 24.72713),
            GeoPoint(60.15885, 24.74241), GeoPoint(60.15054, 24.65307), GeoPoint(60.37752, 25.26906), GeoPoint(60.40338, 25.105),
            GeoPoint(60.46407, 24.8073), GeoPoint(60.47369, 25.08992),
            GeoPoint(60.439696, 24.9384), GeoPoint(60.360117, 25.324158), GeoPoint(60.168792, 25.480769), GeoPoint(59.978575, 25.319704),
            GeoPoint(59.900104, 24.9384), GeoPoint(59.978575, 24.557096), GeoPoint(60.168792, 24.396031), GeoPoint(60.360117, 24.552642),
            GeoPoint(60.575494, 24.9384), GeoPoint(60.455434, 25.520028), GeoPoint(60.167396, 25.753738), GeoPoint(59.881862, 25.509961),
            GeoPoint(59.764306, 24.9384), GeoPoint(59.881862, 24.366839), GeoPoint(60.167396, 24.123062), GeoPoint(60.455434, 24.356772),
            GeoPoint(60.790432, 24.9384), GeoPoint(60.605708, 25.832402), GeoPoint(60.16404, 26.185728), GeoPoint(59.72823, 25.80884),
            GeoPoint(59.549368, 24.9384), GeoPoint(59.72823, 24.06796), GeoPoint(60.16404, 23.691072), GeoPoint(60.605708, 24.044398),
        )
        val entry = Registry.byId("se.cautious")!!
        for (place in places) {
            val resolution = Registry.resolveEntry(entry, Place(place.lat, place.lon, zoneId, "FI"))
            for (date in days) {
                val shown = DayPipeline.unended(resolution, date, zone).maghrib
                assertTrue(shown >= bounds.getValue(date), "the cautious Maghrib at $place on $date: $shown before ${bounds.getValue(date)}")
            }
        }
    }
}
