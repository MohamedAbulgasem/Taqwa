"""Embed the two adhkar resources in the Kotlin tests that read them.

    python3 -I tools/adhkar/embed_test_fixture.py

`Res.readBytes` does not work in the module's tests (the Android host tests have no Android
`Log`, and the iOS ones no app bundle), so `AdhkarCatalogueTest` parses a copy of the bundled
files held in

    shared/src/commonTest/kotlin/world/taqwa/app/adhkar/AdhkarFixtures.kt

and `AdhkarFixturesTest` (androidHostTest) fails whenever the copy differs from the bundled
files. Run this after `build_items.py` to bring the copy back in line. The copy is exact (the
JSON is written as a Kotlin raw string, byte for byte); the script stops if a file holds a
character a raw string cannot carry.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
RESOURCES = os.path.join(ROOT, "shared", "src", "commonMain", "composeResources", "files", "adhkar")
FIXTURE = os.path.join(
    ROOT, "shared", "src", "commonTest", "kotlin", "world", "taqwa", "app", "adhkar", "AdhkarFixtures.kt"
)

HEADER = '''package world.taqwa.app.adhkar

// GENERATED by tools/adhkar/embed_test_fixture.py from the two files below. Do not edit by hand:
// AdhkarFixturesTest fails when this is not exactly the bundled files, and the script brings it back.

/** `files/adhkar/items.json`, as bundled. */
internal val ITEMS_JSON = """'''


def read(name):
    with open(os.path.join(RESOURCES, name), encoding="utf-8", newline="") as f:
        text = f.read()
    for forbidden in ('"""', "$", "\\"):
        if forbidden in text:
            sys.exit(f"{name} contains {forbidden!r}, which a Kotlin raw string cannot carry as is")
    return text


def main():
    items = read("items.json")
    english = read("text/en.json")
    out = (
        HEADER
        + items
        + '"""\n\n/** `files/adhkar/text/en.json`, as bundled. */\ninternal val EN_JSON = """'
        + english
        + '"""\n'
    )
    with open(FIXTURE, "w", encoding="utf-8", newline="") as f:
        f.write(out)
    print(f"wrote {os.path.relpath(FIXTURE, ROOT)} ({len(out.encode('utf-8'))} bytes)")


if __name__ == "__main__":
    main()
